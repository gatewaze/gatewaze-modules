/**
 * Welcome-DM logic that does not touch the network or the database.
 *
 * Kept apart from the routes and the worker so every decision that guards the
 * feature — who sent a request, who an OAuth return belongs to, what a message
 * says, whether a failure is worth retrying — can be unit tested.
 * node:crypto only.
 */

import { createHmac, randomBytes, timingSafeEqual } from 'crypto';

/** User-token scopes the sender authorises: open a DM, and post in it. */
export const USER_SCOPES = ['chat:write', 'im:write'];

/** The purpose a stored user token is for. One connected account per purpose. */
export const WELCOME_PURPOSE = 'welcome_dm';

/**
 * Used until an admin writes their own. Deliberately generic: the message goes
 * out as a real person, so the wording belongs in each install's config.
 */
export const DEFAULT_MESSAGE =
  'Hi {first_name}, welcome to the community! Great to have you here.\n\n' +
  'What are you working on these days?';

/** Slack truncates longer messages; a template this long is a mistake. */
export const MAX_MESSAGE_CHARS = 4000;

/** RFC 5321's limit on a forward path. */
export const MAX_EMAIL_CHARS = 254;

export const DEFAULT_DELAY_MINUTES = 5;
export const MAX_DELAY_MINUTES = 24 * 60;

// ── Slack request signatures ─────────────────────────────────────────────────

/** Slack's documented replay window. */
export const SIGNATURE_MAX_AGE_SECONDS = 5 * 60;

/**
 * Verify an Events API request came from Slack.
 * https://api.slack.com/authentication/verifying-requests-from-slack
 *
 * Signs `v0:<timestamp>:<raw body>` with the app's signing secret. The raw
 * body must be the exact bytes Slack sent: re-serialising parsed JSON changes
 * them and the check fails.
 *
 * @returns {{ok: true} | {ok: false, reason: string}} — the reason is safe to
 *   log; it never contains the secret or the signature.
 */
export function verifySlackSignature({ signingSecret, timestamp, signature, rawBody, now = Date.now() }) {
  if (!signingSecret) return { ok: false, reason: 'signing secret not configured' };
  if (!timestamp || !signature) return { ok: false, reason: 'missing signature headers' };
  if (!/^\d{1,12}$/.test(String(timestamp))) return { ok: false, reason: 'malformed timestamp' };
  const ageSeconds = Math.abs(Math.floor(now / 1000) - Number(timestamp));
  if (ageSeconds > SIGNATURE_MAX_AGE_SECONDS) return { ok: false, reason: 'stale timestamp' };
  if (rawBody == null) return { ok: false, reason: 'no raw body' };

  const body = Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(String(rawBody), 'utf8');
  const expected = 'v0=' + createHmac('sha256', signingSecret)
    .update(`v0:${timestamp}:`)
    .update(body)
    .digest('hex');
  const a = Buffer.from(String(signature), 'utf8');
  const b = Buffer.from(expected, 'utf8');
  if (a.length !== b.length || !timingSafeEqual(a, b)) return { ok: false, reason: 'signature mismatch' };
  return { ok: true };
}

// ── OAuth state ──────────────────────────────────────────────────────────────

/**
 * How long a connect link stays valid. A day, because the link is generated by
 * an admin and then sent to the person whose account it connects; it is bound
 * to that person (see `x`), so a leaked link cannot connect anyone else.
 */
export const STATE_TTL_MS = 24 * 60 * 60 * 1000;
const STATE_MAX_SKEW_MS = 60 * 1000;
const STATE_VERSION = 1;
// A fixed label so a value signed here can never be confused with anything
// else signed with the same secret.
const STATE_LABEL = 'gatewaze.slack.oauth-state.v1.';

const b64url = (buf) => Buffer.from(buf).toString('base64url');

function stateMac(secret, body) {
  return createHmac('sha256', secret).update(STATE_LABEL + body).digest();
}

/**
 * Sign the `state` for the Slack authorize link.
 *
 * @param {{u: string, x: string, t?: string}} input — `u` the admin who
 *   generated the link; `x` the Slack user id that is allowed to complete it;
 *   `t` the workspace it must be completed in (Slack user ids are only unique
 *   within a workspace).
 * @param {string} secret — the app's client secret, which the callback needs
 *   anyway, so no extra secret has to be deployed.
 */
export function signState(input, secret, now = Date.now()) {
  if (!secret) throw new Error('OAuth state secret is not configured');
  if (!input || !input.u || !input.x) throw new Error('state needs the admin (u) and the expected Slack user (x)');
  const payload = { v: STATE_VERSION, u: String(input.u), x: String(input.x), iat: now, n: b64url(randomBytes(16)) };
  if (input.t) payload.t = String(input.t);
  const body = b64url(JSON.stringify(payload));
  return `${body}.${b64url(stateMac(secret, body))}`;
}

/**
 * Check a returned `state`.
 *
 * @returns {{ok: true, state: {u: string, x: string, t: string | null, iat: number}} | {ok: false, reason: string}}
 */
export function checkState(value, secret, now = Date.now()) {
  if (!secret) return { ok: false, reason: 'state secret not configured' };
  if (typeof value !== 'string' || value.length > 2048) return { ok: false, reason: 'malformed state' };
  const parts = value.split('.');
  if (parts.length !== 2 || !/^[A-Za-z0-9_-]+$/.test(parts[0]) || !/^[A-Za-z0-9_-]+$/.test(parts[1])) {
    return { ok: false, reason: 'malformed state' };
  }
  const [body, sig] = parts;
  const given = Buffer.from(sig, 'base64url');
  const expected = stateMac(secret, body);
  if (given.length !== expected.length || !timingSafeEqual(given, expected)) return { ok: false, reason: 'bad signature' };

  let payload;
  try {
    payload = JSON.parse(Buffer.from(body, 'base64url').toString('utf8'));
  } catch {
    return { ok: false, reason: 'malformed state' };
  }
  if (!payload || payload.v !== STATE_VERSION || typeof payload.u !== 'string' || !payload.u
      || typeof payload.x !== 'string' || !payload.x || typeof payload.iat !== 'number'
      || (payload.t !== undefined && (typeof payload.t !== 'string' || !payload.t))) {
    return { ok: false, reason: 'malformed state' };
  }
  if (payload.iat > now + STATE_MAX_SKEW_MS) return { ok: false, reason: 'state from the future' };
  if (now - payload.iat > STATE_TTL_MS) return { ok: false, reason: 'expired' };
  return { ok: true, state: { u: payload.u, x: payload.x, t: payload.t ?? null, iat: payload.iat } };
}

/** The Slack authorize link. User scopes only, so the bot install is untouched. */
export function authorizeUrl({ clientId, redirectUri, state, teamId }) {
  const q = new URLSearchParams({
    client_id: clientId,
    user_scope: USER_SCOPES.join(','),
    redirect_uri: redirectUri,
    state,
  });
  if (teamId) q.set('team', teamId);
  return `https://slack.com/oauth/v2/authorize?${q.toString()}`;
}

// ── Message ──────────────────────────────────────────────────────────────────

/** Slack's three control characters in message text. */
export function escapeSlackText(value) {
  return String(value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function firstNameOf(user) {
  const p = (user && user.profile) || {};
  const candidate = p.first_name || (p.real_name || user?.real_name || '').trim().split(/\s+/)[0] || p.display_name || '';
  return String(candidate).trim();
}

/**
 * Fill the template for one new member.
 *
 * Placeholders: {first_name} and {name}. Names come from the joiner's own
 * profile, so they are escaped — otherwise a display name like `<!channel>`
 * would be a mention. The template itself is the admin's text and is sent as
 * written, so they can use Slack formatting on purpose.
 */
export function renderWelcomeMessage(template, user) {
  const text = (template && String(template).trim()) ? String(template) : DEFAULT_MESSAGE;
  const first = firstNameOf(user) || 'there';
  const full = String(user?.profile?.real_name || user?.real_name || first).trim() || first;
  // Function replacers: a string replacement would treat `$&`, `$1` and the
  // like in someone's name as patterns.
  return text
    .replace(/\{first_name\}/g, () => escapeSlackText(first))
    .replace(/\{name\}/g, () => escapeSlackText(full));
}

/**
 * A Slack error code is safe to show on the callback page only if it looks
 * like one. Anything else in the query string is replaced, not reflected.
 */
export function slackErrorCode(value) {
  return typeof value === 'string' && /^[a-z0-9_]{1,64}$/.test(value) ? value : 'unknown_error';
}

/**
 * Express middleware for the admin routes. The platform gate in front of them
 * already requires a super_admin JWT; this refuses anything that reaches the
 * router without a signed-in user, so a hole in that gate does not open these.
 */
export function requireSignedIn(req, res, next) {
  if (req && typeof req.userId === 'string' && req.userId) return next();
  return res.status(401).json({ error: 'not signed in' });
}

// ── Who gets one ─────────────────────────────────────────────────────────────

/**
 * @returns {{ok: true} | {ok: false, reason: string}}
 */
export function isWelcomable(user, senderSlackUserId) {
  if (!user || typeof user.id !== 'string' || !user.id) return { ok: false, reason: 'no user' };
  if (user.id === 'USLACKBOT') return { ok: false, reason: 'slackbot' };
  if (user.is_bot || user.is_app_user) return { ok: false, reason: 'bot' };
  if (user.deleted) return { ok: false, reason: 'deactivated' };
  if (senderSlackUserId && user.id === senderSlackUserId) return { ok: false, reason: 'is the sender' };
  return { ok: true };
}

/** Clamp the configured delay to something sane. */
export function delayMs(minutes) {
  const n = Number(minutes);
  const m = Number.isFinite(n) && n >= 0 ? Math.min(n, MAX_DELAY_MINUTES) : DEFAULT_DELAY_MINUTES;
  return Math.round(m * 60 * 1000);
}

// ── Failures ─────────────────────────────────────────────────────────────────

const AUTH_ERRORS = new Set([
  'invalid_auth', 'not_authed', 'token_revoked', 'token_expired', 'account_inactive',
  'missing_scope', 'no_permission', 'ekm_access_denied', 'not_allowed_token_type',
]);
const PERMANENT_ERRORS = new Set([
  'user_not_found', 'users_not_found', 'cannot_dm_bot', 'user_disabled', 'channel_not_found',
  'is_archived', 'msg_too_long', 'no_text', 'invalid_blocks', 'restricted_action',
  'not_in_channel', 'user_is_restricted', 'user_is_ultra_restricted', 'method_not_supported_for_channel_type',
]);

/**
 * What to do about a Slack error code.
 *
 * @returns {'auth' | 'permanent' | 'retry'} — `auth` means the connected
 *   account no longer works and every later send will fail the same way;
 *   `permanent` means this one recipient cannot be messaged; anything else
 *   (rate limits, Slack outages, network errors, unknown codes) is retried a
 *   bounded number of times.
 */
export function classifySlackError(code) {
  if (AUTH_ERRORS.has(code)) return 'auth';
  if (PERMANENT_ERRORS.has(code)) return 'permanent';
  return 'retry';
}
